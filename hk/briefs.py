"""Editable contractor job briefs (section 4G of the brief).

A brief is a plain Markdown file the owner can edit and send. It contains only what the house
record documents — the observed issue, location/equipment, relevant history, attached document
references, questions to ask, and what a comparable quote must include. It never states a diagnosis
the record does not support.
"""
from __future__ import annotations

import pathlib

from . import HOUSES
from .evidence import Profile
from .rules import Task
from . import actions

QUESTIONS_BY_CATEGORY = {
    "roofer": ["Will you inspect the whole roof and flashings, or only the area noted?",
               "Is the quote for repair, or does it assume replacement? What would change that?",
               "What is excluded (decking, flashing, chimney counter-flashing, disposal)?",
               "Workmanship warranty length? Manufacturer warranty on materials?",
               "PA HICPA registration number (must appear on the contract)? Certificate of insurance?"],
    "hvac": ["Will the visit include a combustion/CO test with a written reading?",
             "What is included in 'annual service' (list the items)?",
             "Do you register new equipment for warranty, and who files it?",
             "PA HICPA registration number? Certificate of insurance?"],
    "plumber": ["Are you an Allegheny County Health Department registered master plumber (HP number)?",
                "Will a county plumbing permit be pulled where required, and is it in the price?",
                "What is excluded (wall/floor repair, drywall, disposal of old unit)?",
                "Warranty on labor and on the part/unit?"],
    "electrician": ["Are you licensed where this house is (City of Pittsburgh trade license, or municipal registration)?",
                    "Will a permit and inspection be pulled, and is it in the price?",
                    "Does the quote include any panel/service work, or only the item noted?",
                    "PA HICPA registration number? Certificate of insurance?"],
    "chimney": ["Is this a CSIA-certified sweep? Which inspection level is quoted (Level 1 or 2)?",
                "Will you report on the liner condition in writing with photos?",
                "Is sweeping included if 1/8 in of buildup is found?"],
    "radon": ["Are you PA DEP certified (DEP ID number) for mitigation?",
              "Where will the fan and discharge be placed, and will a manometer be installed?",
              "Is the post-mitigation test included, and who performs it?"],
}
GENERIC_QUESTIONS = ["What exactly is included and excluded?",
                     "When can the work start and how long will it take?",
                     "What warranty applies, and is it in writing?",
                     "PA HICPA registration number (contractors over $5,000/yr must register; number must appear on the contract)?",
                     "Will you provide a certificate of insurance?"]


def brief_text(p: Profile, task: Task) -> str:
    comp = task.component
    eq = p.installed(comp) if comp else None
    docs = [d for d in (getattr(p, "documents", None) or []) if d.get("component") == comp or d.get("rule_id") == task.rule_id]
    comps = [c for c in (getattr(p, "completions", None) or []) if c.get("component") == comp or c.get("rule_id") == task.rule_id]
    fnds = [f for f in p.findings if f["component"] == comp]
    est = None
    for e in reversed(getattr(p, "estimates", None) or []):
        if e["applies_to"] in (task.rule_id, comp):
            est = e; break
    addr = p.value("matched_address") or p.address_input
    out = [f"# Job brief — {task.title}", "",
           f"_Editable draft generated by HomeKeeper on {p.updated}. Edit anything before sending. Facts below come from the house record; nothing here is a diagnosis._", "",
           "## Property", f"- Address: {addr}", f"- Built: {p.value('year_built') or 'unknown'}; {p.value('stories') or '?'} stories; basement: {p.value('basement') or 'unknown'}; exterior: {p.value('exterior_finish') or 'unknown'}",
           f"- Municipality: {p.value('municipality') or 'unknown'}", "",
           "## Requested service / observed issue"]
    if task.status == "finding":
        f = next((f for f in p.findings if f"FINDING-{f['id']}" == task.rule_id), None)
        if f:
            out.append(f"- Documented in {f['source_doc']}" + (f" ({f['observed_date']})" if f.get('observed_date') else "") + f": {f['description']}")
            if f.get("location"): out.append(f"- Location: {f['location']}")
            if f.get("recommendation"): out.append(f"- Inspector's recommendation: {f['recommendation']}")
    else:
        out.append(f"- {task.action}")
        out.append(f"- Why it applies here: {task.why}")
    out += ["", "## Affected location / equipment"]
    if eq:
        out.append(f"- {comp}: {eq.get('make','')} {eq.get('model','')} installed {eq.get('installed_year') or '?'}"
                   + (f"; last service {eq['last_service_date']}" if eq.get('last_service_date') else "")
                   + (f"; manual on file ({eq['manual_source_id']})" if eq.get('manual_source_id') else ""))
    else:
        out.append(f"- {comp or 'see above'} — no equipment record (make/model unknown)")
    out += ["", "## Relevant history"]
    for c in comps:
        out.append(f"- {c['date']}: {c['rule_id']} — {c.get('notes','')}" + (f" ({c['contractor']})" if c.get('contractor') else ""))
    for f in fnds:
        if f"FINDING-{f['id']}" != task.rule_id:
            out.append(f"- Finding {f['id']} ({f['status']}): {f['description']}")
    if not comps and len(fnds) <= (1 if task.status == "finding" else 0):
        out.append("- none recorded")
    out += ["", "## Photos and documents available"]
    out += [f"- {d['kind']}: {d['title']} ({d['ref']})" for d in docs] or ["- none attached yet"]
    out += ["", "## Questions to ask"]
    out += [f"- {q}" for q in QUESTIONS_BY_CATEGORY.get(task.provider_category, GENERIC_QUESTIONS)]
    if task.provider_category in QUESTIONS_BY_CATEGORY:
        out += [f"- {q}" for q in GENERIC_QUESTIONS[:2]]
    out += ["", "## For a comparable quote, please state",
            "- Scope (what is and is not included), materials/model numbers, labor",
            "- Permits and inspections (who pulls them; included or extra)",
            "- Timeline, payment terms, warranty terms in writing",
            "- Your PA HICPA registration number and insurance certificate"]
    if est:
        out += ["", f"_Existing estimate on file: ${est['low']:,.0f}–${est['high']:,.0f} ({est['basis']}; {est['source']}, {est['date']}; scope: {est['scope']})_"]
    out += ["", f"_Provider category: {task.provider_category or 'unspecified'}. HomeKeeper does not contact providers or share this brief; you do._"]
    return "\n".join(out)


def write_brief(p: Profile, task: Task) -> pathlib.Path:
    d = HOUSES / p.house_id / "briefs"
    d.mkdir(parents=True, exist_ok=True)
    path = d / f"{task.rule_id}.md"
    path.write_text(brief_text(p, task), encoding="utf-8")
    actions.add_document(p, kind="brief", title=f"Job brief: {task.title}", ref=str(path), component=task.component,
                         rule_id=task.rule_id, note="editable Markdown; regenerate with 'brief' to refresh facts")
    return path
